class ProductTemplateAlignerV2:
    def __init__(
        self,
        model_name: str = APP_SETTINGS.model_name,
        provider_name: str = APP_SETTINGS.provider_name,
    ):
        self.model = f"{provider_name}/{model_name}"

    async def invoke(self, product_document: str) -> FilledProduct:
        """
        Оркестрирует процесс генерации полного объекта FilledProduct.
        """
        print(f"Начинаю генерацию шаблона для документа (первые 100 символов): {product_document[:100]}...")

        # Запускаем обе задачи параллельно для ускорения
        info_task = asyncio.create_task(self._fill_product_info(product_document))
        shots_task = asyncio.create_task(self._fill_few_shots(product_document))

        product_info, few_shots = await asyncio.gather(info_task, shots_task)

        filled_product = FilledProduct(info=product_info, few_shots=few_shots)
        print("Генерация шаблона успешно завершена.")
        return filled_product

    async def _fill_product_info(self, product_document: str) -> ProductInfo:
        """
        Генерирует и валидирует объект ProductInfo с помощью LLM.
        """
        print("Этап 1: Генерация основной информации о продукте (ProductInfo)...")
        schema = json.dumps(ProductInfo.model_json_schema(by_alias=False), indent=2, ensure_ascii=False)
        system_prompt = PRODUCT_INFO_GENERATION_PROMPT.format(
            example_info_product_name=GOLDEN_EXAMPLE_BONDS.info.name,
            example_info_doc=GOLDEN_EXAMPLE_DOC,
            example_info_json=GOLDEN_EXAMPLE_BONDS.info.model_dump_json(indent=4),
        )  # json_schema=schema)

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": f"<INPUT_DOCUMENT>\n{product_document}\n</INPUT_DOCUMENT>"},
        ]

        try:
            response = await litellm.acompletion(model=self.model, messages=messages)
            content = repair_json(response.choices[0].message.content, True)
            product_info = ProductInfo(**content)
            print("Этап 1: Успешно.")
            return product_info
        except (json.JSONDecodeError, ValidationError) as e:
            print(f"Ошибка валидации или парсинга JSON на этапе 1: {e}")
            raise
        except Exception as e:
            print(f"Ошибка при вызове LLM на этапе 1: {e}")
            raise

    async def _fill_few_shots(self, product_document: str) -> List[ProductFewShot]:
        """
        Генерирует и валидирует список объектов ProductFewShot с помощью LLM.
        """
        print("Этап 2: Генерация обучающих примеров (FewShots)...")
        schema = json.dumps(ProductFewShot.model_json_schema(by_alias=False), indent=2, ensure_ascii=False)
        system_prompt = FEW_SHOTS_GENERATION_PROMPT.format(
            example_info_product_name=GOLDEN_EXAMPLE_BONDS.info.name,
            example_info_doc=GOLDEN_EXAMPLE_DOC,
            example_few_shots_json=GOLDEN_EXAMPLE_BONDS.info.model_dump_json(indent=4),
        )

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": f"<INPUT_DOCUMENT>\n{product_document}\n</INPUT_DOCUMENT>"},
        ]

        try:
            response = await litellm.acompletion(model=self.model, messages=messages)
            data = repair_json(response.choices[0].message.content, True)
            # Ожидаем ответ в формате {"examples": [...]}
            few_shots = []
            for item in data["examples"]:
                try:
                    few_shots.append(ProductFewShot(**item))
                except Exception:
                    pass
            print("Этап 2: Успешно.")
            return few_shots
        except (json.JSONDecodeError, ValidationError, KeyError) as e:
            print(f"Ошибка валидации или парсинга JSON на этапе 2: {e}")
            raise
        except Exception as e:
            print(f"Ошибка при вызове LLM на этапе 2: {e}")
            raise


